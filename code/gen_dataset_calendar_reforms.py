def year_to_num(s):
    """『前104』→ -104；『1281』→ 1281；空 → 空。"""
    if s is None or s == "":
        return ""
    t = str(s).strip()
    if t.startswith("前"):
        return -int(t[1:])
    try:
        return int(t)
    except ValueError:
        return ""


def main():
    out = sys.argv[1]
    d = os.path.join(out, "02-历代历法改革年表", "data")
    os.makedirs(d, exist_ok=True)

    cols = ["序号", "历法名", "朝代_政权", "行用起年", "行用止年",
            "行用起年_数值", "行用止年_数值", "主要编者",
            "岁实_回归年_日", "朔望月_日", "岁首_斗建", "重大改动", "依据"]
    p = os.path.join(d, "calendar_reforms.csv")
    with io.open(p, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(cols)
        for r in ROWS:
            (i, name, dyn, y0, y1, ed, ss, sy, shou, chg, src) = r
            w.writerow([i, name, dyn, y0, y1, year_to_num(y0), year_to_num(y1),
                        ed, ss, sy, shou, chg, src])
    print("写出", p, len(ROWS), "行")

    kp = os.path.join(d, "kaoyi_discrepancies.csv")
    with io.open(kp, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["条目", "来源甲", "来源乙", "本表处理"])
        w.writerows(KAOYI)
    print("写出", kp, len(KAOYI), "行")

    # 自检：序号连续；起止年格式；建寅一致性
    idxs = [r[0] for r in ROWS]
    assert idxs == list(range(1, len(ROWS) + 1)), "序号不连续"
    bad = [r[1] for r in ROWS if r[3] and year_to_num(r[3]) == ""]
    print("序号连续性：通过（1—%d）" % len(ROWS))
    print("起年不可解析：", bad if bad else "无")
    # 起止年先后自检
    rev = []
    for r in ROWS:
        a, b = year_to_num(r[3]), year_to_num(r[4])
        if a != "" and b != "" and a > b:
            rev.append((r[1], r[3], r[4]))
    print("起年晚于止年：", rev if rev else "无")
    n_ss = sum(1 for r in ROWS if r[6])
    print("含岁实的行数：%d / %d（其余留空，不臆补）" % (n_ss, len(ROWS)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
